<#
.SYNOPSIS
  Verifies that every shipped dependency uses an allowed license (Constitution IV) and writes
  THIRD-PARTY-NOTICES.md.

.DESCRIPTION
  NuGet: all packages resolved for src/Copernica (including transitive ones), read from the
  local package cache (.nuspec). Design-time-only packages (PrivateAssets=all) are skipped.
  npm: production dependencies of src/web (what is bundled into the browser code).
  Exits with code 1 when a license is not on the allow-list.
#>
[CmdletBinding()]
param(
    [switch] $NoNotices
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot

$allowed = @('MIT', 'Apache-2.0', 'BSD-2-Clause', 'BSD-3-Clause', 'ISC', '0BSD', 'Unlicense', 'MIT OR Apache-2.0', 'Apache-2.0 OR MIT', 'PostgreSQL')

# Packages whose nuspec has no SPDX expression; license verified by hand and recorded here.
$knownLicenses = @{
    'LibGit2Sharp.NativeBinaries'                   = 'GPL-2.0-with-linking-exception (libgit2; allowed by Constitution IV, see SECURITY.md)'
    'System.Security.Cryptography.ProtectedData'    = 'MIT'
    'LibGit2Sharp'                                  = 'MIT'
}

# Build/design-time only (EF Core tooling); not part of the published application.
$designTime = @('Microsoft.EntityFrameworkCore.Design', 'Microsoft.CodeAnalysis', 'Microsoft.Build', 'Mono.TextTemplating',
    'Humanizer.Core', 'Microsoft.VisualStudio.SolutionPersistence', 'System.CodeDom', 'System.Composition', 'Microsoft.Bcl.AsyncInterfaces')

$results = [System.Collections.Generic.List[object]]::new()
$failures = [System.Collections.Generic.List[string]]::new()

# --- NuGet -----------------------------------------------------------------------------------
$json = dotnet list (Join-Path $root 'src/Copernica') package --include-transitive --format json | ConvertFrom-Json
$cache = (dotnet nuget locals global-packages --list) -replace '^global-packages:\s*', ''
$packages = $json.projects.frameworks |
    ForEach-Object { $_.topLevelPackages + $_.transitivePackages } |
    Where-Object { $_ } |
    Sort-Object id -Unique

foreach ($package in $packages) {
    $id = $package.id
    if ($designTime | Where-Object { $id -like "$_*" }) { continue }
    $version = $package.resolvedVersion
    $nuspec = Join-Path $cache "$($id.ToLowerInvariant())/$version/$($id.ToLowerInvariant()).nuspec"
    $license = $null
    if (Test-Path $nuspec) {
        [xml] $xml = Get-Content $nuspec
        $node = $xml.package.metadata.license
        if ($node -and $node.type -eq 'expression') { $license = $node.'#text' }
    }
    if (-not $license -and $knownLicenses.ContainsKey($id)) { $license = $knownLicenses[$id] }
    $ok = $license -and (($allowed -contains $license) -or $knownLicenses.ContainsKey($id))
    if (-not $ok) { $failures.Add("NuGet $id $version : $license") }
    $results.Add([pscustomobject]@{ Ecosystem = 'NuGet'; Name = $id; Version = $version; License = $license ?? 'UNKNOWN' })
}

# --- npm (bundled into the browser) ------------------------------------------------------------
$web = Join-Path $root 'src/web'
# npm packages whose manifest has no single SPDX id we allow; license verified by hand (004 research R7).
$knownNpmLicenses = @{
    'dompurify' = 'Apache-2.0 (dual MPL-2.0 OR Apache-2.0; used under Apache-2.0)'
    'khroma'    = 'MIT (LICENSE file; no license field in package.json)'
}

$paths = npm --prefix $web ls --omit=dev --all --parseable 2>$null | Select-Object -Skip 1
foreach ($path in ($paths | Sort-Object -Unique)) {
    $manifest = Get-Content (Join-Path $path 'package.json') -Raw | ConvertFrom-Json
    $license = if ($manifest.license -is [string]) { $manifest.license } else { $manifest.license.type }
    if ($knownNpmLicenses.ContainsKey($manifest.name)) { $license = $knownNpmLicenses[$manifest.name] }
    elseif ($allowed -notcontains $license) { $failures.Add("npm $($manifest.name) $($manifest.version) : $license") }
    $results.Add([pscustomobject]@{ Ecosystem = 'npm'; Name = $manifest.name; Version = $manifest.version; License = $license ?? 'UNKNOWN' })
}

$results = $results | Sort-Object Ecosystem, Name -Unique

if (-not $NoNotices) {
    $lines = @(
        '# Third-party notices',
        '',
        'Generated by `scripts/check-licenses.ps1`. Lists every dependency shipped in the Copernica executable',
        'and container image (NuGet) or bundled into the web UI (npm).',
        '',
        '| Ecosystem | Package | Version | License |',
        '|-----------|---------|---------|---------|'
    ) + ($results | ForEach-Object { "| $($_.Ecosystem) | $($_.Name) | $($_.Version) | $($_.License) |" })
    Set-Content -Path (Join-Path $root 'THIRD-PARTY-NOTICES.md') -Value $lines -Encoding utf8NoBOM
}

Write-Host "$($results.Count) shipped dependencies checked."
if ($failures.Count -gt 0) {
    Write-Host 'Dependencies with licenses outside the allow-list:' -ForegroundColor Red
    $failures | ForEach-Object { Write-Host "  $_" -ForegroundColor Red }
    exit 1
}

Write-Host 'All licenses are allowed.' -ForegroundColor Green
